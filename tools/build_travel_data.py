#!/usr/bin/env python3
"""Builds TravelData.lua from OpenMap's data tables (MIT, see LICENSES/OpenMap.txt).

OpenMap generates its tables from WoW Forever's own game tables. This keeps
what the route planner needs: where the flight masters and the boat, zeppelin
and airship docks are, and how long each flight path is.

Usage: tools/build_travel_data.py <path to the OpenMap addon folder>
"""
import math
import re
import sys
from pathlib import Path

NEAR_YARDS = 700          # a dock this close to a flight master takes its name
NEUTRAL_BOATS = {"Booty Bay - Ratchet", "Steamwheedle Port - Powderfuse Port"}
FACTION = {1: "A", 2: "H", 3: "B"}


def num(text):
    value = float(text)
    return int(value) if value == int(value) else value


def lua_number(value):
    return str(value) if isinstance(value, int) else f"{value:.1f}"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = Path(sys.argv[1]) / "Data" / "Forever"
    flights = (source / "FlightData.lua").read_text(encoding="utf-8")
    places = (source / "Places.lua").read_text(encoding="utf-8")
    build = re.search(r"build ([\d.]+)", flights)

    nodes = {}
    node_block = flights[flights.index("nodes = {"):flights.index("paths = {")]
    for match in re.finditer(
            r'\[(\d+)\] = \{ "([^"]+)", (-?\d+), (-?[\d.]+), (-?[\d.]+), (\d+)(, "[A-Z]+")? \}', node_block):
        node, name, continent, x, y, factions, only_class = match.groups()
        if only_class or int(continent) not in (0, 1) and int(continent) < 100:
            continue   # one class only, or a battleground
        nodes[int(node)] = (name, int(continent), num(x), num(y), FACTION[int(factions)])

    paths = []
    path_block = flights[flights.index("paths = {"):]
    for match in re.finditer(r"\{ (\d+), (\d+), (\d+), \d+, \{", path_block):
        start, end, yards = (int(part) for part in match.groups())
        if start in nodes and end in nodes:
            paths.append((start, end, yards))

    def nearest(continent, x, y):
        best, best_yards = None, NEAR_YARDS
        for node, (_, node_continent, nx, ny, _) in nodes.items():
            if node_continent == continent:
                yards = math.hypot(nx - x, ny - y)
                if yards < best_yards:
                    best, best_yards = node, yards
        return best

    transports = []
    block = places[places.index("transports = {"):places.index("sailings = {")]
    for match in re.finditer(
            r'\{ "(\w+)", "([^"]+)", (\d+), (-?[\d.]+), (-?[\d.]+), (\d+), (-?[\d.]+), (-?[\d.]+) \}', block):
        kind, route, continent, x, y, to_continent, to_x, to_y = match.groups()
        continent, to_continent = int(continent), int(to_continent)
        x, y, to_x, to_y = num(x), num(y), num(to_x), num(to_y)
        if kind == "zeppelin":
            faction = "H"
        elif kind == "boat":
            faction = "B" if route in NEUTRAL_BOATS else "A"
        else:
            faction = "B"
        transports.append((kind, route, faction, continent, x, y, nearest(continent, x, y),
                           to_continent, to_x, to_y, nearest(to_continent, to_x, to_y)))

    out = [
        "-- Where WoW Forever's flight masters and boat, zeppelin and airship docks are,",
        "-- and how long each flight path is. Positions are world yards per continent",
        "-- (0 Eastern Kingdoms, 1 Kalimdor), x north and y west, as the game gives them.",
        "--",
        "-- Generated by tools/build_travel_data.py from OpenMap's data tables",
        f"-- (game build {build.group(1) if build else '?'}). OpenMap is MIT licensed:",
        "-- Copyright (c) 2026 OpenMap contributors, see LICENSES/OpenMap.txt.",
        "-- Regenerate rather than edit.",
        "--",
        "--   nodes[id]     = { name, continent, x, y, faction }   faction: A, H or B (both)",
        "--   flights[i]    = { from, to, yards }                  one way",
        "--   transports[i] = { kind, route, faction, continent, x, y, node,",
        "--                     toContinent, toX, toY, toNode }     one way; node: the flight",
        "--                     master next to that dock, or false",
        "",
        "local _, ns = ...",
        "",
        "ns.TravelData = {",
        "    nodes = {",
    ]
    for node in sorted(nodes):
        name, continent, x, y, faction = nodes[node]
        out.append(f'        [{node}] = {{ "{name}", {continent}, {lua_number(x)}, {lua_number(y)}, "{faction}" }},')
    out += ["    },", "    flights = {"]
    line = []
    for start, end, yards in paths:
        line.append(f"{{ {start}, {end}, {yards} }},")
        if len(line) == 6:
            out.append("        " + " ".join(line))
            line = []
    if line:
        out.append("        " + " ".join(line))
    out += ["    },", "    transports = {"]
    for kind, route, faction, continent, x, y, node, to_continent, to_x, to_y, to_node in transports:
        out.append(
            f'        {{ "{kind}", "{route}", "{faction}", {continent}, {lua_number(x)}, {lua_number(y)}, '
            f'{node or "false"}, {to_continent}, {lua_number(to_x)}, {lua_number(to_y)}, {to_node or "false"} }},')
    out += ["    },", "}", ""]
    Path(__file__).resolve().parent.parent.joinpath("TravelData.lua").write_text("\n".join(out), encoding="utf-8")
    print(f"{len(nodes)} flight masters, {len(paths)} flight paths, {len(transports)} transports")


if __name__ == "__main__":
    main()
